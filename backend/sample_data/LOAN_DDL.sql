CREATE TABLE CLAIMS.LOAN_MASTER (
    LOAN_ID      CHAR(10)     NOT NULL,
    CUST_ID      CHAR(10)     NOT NULL,
    LOAN_AMT     DECIMAL(12,2),
    INT_RATE     DECIMAL(5,3),
    START_DATE   DATE,
    END_DATE     DATE,
    STATUS       CHAR(2),
    PRIMARY KEY (LOAN_ID)
);

CREATE INDEX IX_LOAN_CUST ON CLAIMS.LOAN_MASTER (CUST_ID);

SELECT LOAN_ID, LOAN_AMT, STATUS
FROM   CLAIMS.LOAN_MASTER
WHERE  STATUS = 'AC'
ORDER BY START_DATE DESC;
