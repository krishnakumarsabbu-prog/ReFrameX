CREATE TABLE EMPLOYEE.EMP_MASTER (
    EMP_ID       CHAR(6)     NOT NULL,
    EMP_NAME     VARCHAR(30) NOT NULL,
    EMP_DEPT     CHAR(10),
    EMP_SALARY   DECIMAL(9,2),
    HIRE_DATE    DATE,
    PRIMARY KEY (EMP_ID)
);

CREATE INDEX IX_EMP_DEPT ON EMPLOYEE.EMP_MASTER (EMP_DEPT);

CREATE VIEW EMP_ACTIVE_VIEW AS
SELECT EMP_ID, EMP_NAME, EMP_DEPT
FROM   EMPLOYEE.EMP_MASTER
WHERE  EMP_DEPT IS NOT NULL;

