-- Claims transaction tables and procedures
CREATE TABLE CLAIMS.CLAIM_TRANS (
    CLAIM_ID     CHAR(10)     NOT NULL,
    POLICY_ID    CHAR(10)     NOT NULL,
    CLAIM_AMT    DECIMAL(10,2),
    CLAIM_DATE   DATE,
    CLAIM_STATUS CHAR(2),
    PRIMARY KEY (CLAIM_ID)
);

CREATE INDEX IX_CLAIM_POL ON CLAIMS.CLAIM_TRANS (POLICY_ID);

CREATE PROCEDURE CLAIMS.PROC_ADJ_CLAIM (
    IN P_CLAIM_ID CHAR(10),
    IN P_ADJ_AMT  DECIMAL(10,2)
)
LANGUAGE SQL
BEGIN
    UPDATE CLAIMS.CLAIM_TRANS
    SET    CLAIM_AMT = P_ADJ_AMT
    WHERE  CLAIM_ID = P_CLAIM_ID;
END;

-- Merge for reconciliation
MERGE INTO CLAIMS.CLAIM_TRANS AS T
USING CLAIMS.CLAIM_STAGING AS S
ON T.CLAIM_ID = S.CLAIM_ID
WHEN MATCHED THEN UPDATE SET T.CLAIM_AMT = S.CLAIM_AMT;
